#!/usr/bin/env bash
# Thunderbird does not follow the GTK theme in its own window. It is themed
# the way a Firefox profile is: a stylesheet, one import in userChrome.css,
# and one user.js line, under its own framework and its own manifest key.
# It writes inside mail profiles, so it is opt-in. Everything here runs
# against a throwaway HOME; no real Thunderbird profile is read or touched.
REPO=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
set -uo pipefail
chk(){ [[ $2 == "$3" ]] && echo "  PASS $1" || echo "  FAIL $1: got [$2] want [$3]"; }

python3 - "$REPO" <<'E'
import json, os, re, sys, tempfile, types
from pathlib import Path

REPO = sys.argv[1]
root = Path(os.path.realpath(tempfile.mkdtemp()))
os.environ["HOME"] = str(root)
os.environ["XDG_RUNTIME_DIR"] = str(root / "run")
(root / "run").mkdir(mode=0o700)
helper = REPO + "/lib/hyprchroma-state"
st = types.ModuleType("st")
st.__dict__["__file__"] = helper
exec(compile(open(helper).read(), "st", "exec"), st.__dict__)

def chk(name, got, want):
    print(f"  {'PASS' if got == want else 'FAIL'} {name}"
          + ("" if got == want else f": got [{got}] want [{want}]"))

spawned = []
st.spawn_thunderbird_waiter = lambda *a: spawned.append(a)
holders = []
st.profile_holders = lambda profile: list(holders)

S, D = root / "state", root / "share"
S.mkdir(); D.mkdir()
PALETTE = {"mode": "dark", "background": "#1a1b26", "dark_background": "#16161e",
           "foreground": "#c0caf5", "accent": "#7aa2f7", "selection": "#33467c",
           "selection_foreground": "#c0caf5", "muted": "#565f89"}

def palette():
    (D / "thunderbird-theme.json").write_text(json.dumps(PALETTE))

def sync(revert=False):
    return st.sync_thunderbird(S, D, revert=revert, spawn=False)

def manifest():
    return st.read_json(S / "original" / "manifest.json")

def ini(directory, *rows):
    directory.mkdir(parents=True, exist_ok=True)
    directory.joinpath("profiles.ini").write_text(
        "[General]\nStartWithLastProfile=1\n\n" + "".join(
            f"[Profile{n}]\nName=p{n}\nIsRelative={rel}\nPath={path}\n\n"
            for n, (path, rel) in enumerate(rows)))

# -- nothing installed --------------------------------------------------------
chk("no Thunderbird: reported, and nothing written",
    (st.sync_thunderbird(S, D)[0], (S / "original").exists()), ("not-installed", False))

# -- discovery: profiles.ini under the known roots, and nowhere else ----------
native = root / ".thunderbird"
outside = root / "outside"; outside.mkdir()
(root / "escape").mkdir()
mail = native / "mail.default"; mail.mkdir(parents=True)
ini(native, ("mail.default", 1), (str(outside), 0), ("../../escape", 1))
found = [p.name for p in st.thunderbird_profiles()]
chk("a relative profile under ~/.thunderbird is found", found, ["mail.default"])
chk("an absolute profile outside that folder is refused",
    any(str(outside) in str(p) for p in st.thunderbird_profiles()), False)
chk("a profile that climbs out with .. is refused",
    any("escape" in str(p) for p in st.thunderbird_profiles()), False)

flat = root / ".var/app/org.mozilla.Thunderbird/.thunderbird"
(flat / "flat.default").mkdir(parents=True)
ini(flat, ("flat.default", 1))
chk("the Flatpak root is found too",
    sorted(p.name for p in st.thunderbird_profiles()), ["flat.default", "mail.default"])

ff = root / ".mozilla/firefox/other.default"
ff.mkdir(parents=True)
ini(ff.parent, ("other.default", 1))
chk("a Firefox profile is not a Thunderbird profile",
    "other.default" in [p.name for p in st.thunderbird_profiles()], False)

# -- sync writes the sheet, and only into Thunderbird's own record -----------
palette()
state, summary, pids = sync()
sheet = (mail / "chrome/hyprchroma.css").read_text()
chk("a profile is themed", (state, summary, pids), ("synchronized", "Thunderbird", []))
chk("the sheet is Thunderbird's layout tokens, carrying the palette",
    ("--layout-background-2: #16161e" in sheet, "--tree-view-bg: #1a1b26" in sheet,
     "--toolbox-background-color" in sheet, "Generated by Hyprchroma" in sheet),
    (True, True, False, True))
def stylesheet(**colors):
    return st.thunderbird_stylesheet({**PALETTE, **colors})

def var(css, name):
    return re.search(re.escape(name) + r": ([^;]+?) !important;", css).group(1)

# System colors: chat panels, search fields and tree headers paint these
# directly, so no variable reaches them. Each has to be named.
for rule in (".im-placeholder-screen", ".themeableSearchBox", "#listPaneBox", "#chat-toolbar",
             "#navigation-toolbox", ".contentTabInstance", "treecol", ".calendar-enable-button"):
    chk(f"{rule} is painted from the palette", rule in sheet, True)
# Toolbar icons are SVG documents the sheet also applies to: a background on
# :root makes each a solid square. The mini-calendar's month and year are inputs
# meant to be transparent, so bare input is out too.
blocks = re.findall(r"([^{}]*)\{([^{}]*)\}", sheet)
chk("no rule paints :root or a bare input",
    [sel.strip() for sel, body in blocks if re.search(r"(?<![\\w-])background(-color)?\\s*:", body)
     and re.search(r"(^|,)\s*(:root|input|textarea)\s*(,|$)", sel.strip())], [])
# --selected-item-color is Thunderbird's accent, read as text as well as fill.
chk("the accent variable carries the accent, its text partner the selection's",
    (var(sheet, "--selected-item-color"), var(sheet, "--selected-item-text-color")),
    (PALETTE["accent"], PALETTE["selection_foreground"]))
# A selection color made for its own foreground (Scotch's is the theme's own
# foreground) cannot go under the normal text an unfocused row keeps: that drew
# selected folders and contacts at 1:1.
scotch = {"background": "#2e342d", "dark_background": "#232722", "foreground": "#d4cab1",
          "accent": "#b8603d", "selection": "#d4cab1", "selection_foreground": "#090f08",
          "muted": "#636762"}
css = stylesheet(**scotch)
chk("a selection that normal text cannot read on is not used under it",
    ("color-mix" in var(css, "--listbox-selected-bg"),
     "color-mix" in var(css, "--toolbarbutton-checked-background")), (True, True))
chk("...while fills with their own text keep it",
    (var(css, "--listbox-focused-selected-bg"), var(css, "--treeitem-background-active")),
    ("#d4cab1", "#d4cab1"))
chk("a selection normal text reads on is used as is",
    var(sheet, "--listbox-selected-bg"), PALETTE["selection"])
# Accent as text, and text on the accent.
chk("contrast is measured as WCAG defines it",
    (round(st.contrast_ratio("#000000", "#ffffff"), 1), round(st.contrast_ratio("#777777", "#777777"), 1)),
    (21.0, 1.0))
chk("text on a mid-tone accent falls back to black or white when neither end reads",
    st.readable_text_on("#b8603d", "#d4cab1", "#2e342d"), "#000000")
chk("...and stays in the palette when one does",
    st.readable_text_on("#f945d9", "#ece5ed", "#110016"), "#110016")
chk("an accent too faint as text is moved until it reads",
    st.contrast_ratio(st.readable_accent("#b8603d", "#d4cab1", "#2e342d"), "#2e342d") >= 4.5, True)
chk("...and one that reads is left as it is",
    st.readable_accent("#f945d9", "#ece5ed", "#110016"), "#f945d9")
content = st.thunderbird_content_stylesheet(PALETTE)
for page in ("about:addressbook", "about:preferences", "about:addons", "about:accountsettings"):
    chk(f"{page} is themed through the content sheet", f'url-prefix("{page}")' in content, True)
chk("a mail message is not", ("imap:" in content, "mailbox:" in content), (False, False))
chk("userChrome.css gains the one import",
    (mail / "chrome/userChrome.css").read_text().strip(), st.USERCHROME_IMPORT)
chk("the start page gets its own sheet, not the chrome one",
    ((mail / "chrome/userContent.css").read_text().strip(),
     "start.thunderbird.net" in (mail / "chrome/hyprchroma-content.css").read_text(),
     "start.thunderbird.net" in sheet),
    (st.USERCONTENT_IMPORT, True, False))
chk("user.js gains the one preference",
    (mail / "user.js").read_text().strip(), st.USERJS_PREF)
record = manifest().get("thunderbird", {}).get("profiles", {}).get(str(mail))
chk("the capture is under thunderbird, not browsers",
    (isinstance(record, dict), "browsers" in manifest(), record.get("stylesheetsPref")),
    (True, False, False))
chk("the Firefox profile was not touched", (ff / "chrome").exists(), False)

# -- a linked user.js is refused, and that profile is left untouched ---------
linked = native / "linked.default"
linked.mkdir()
(linked / "user.js").symlink_to(outside / "user.js")
ini(native, ("mail.default", 1), ("linked.default", 1), (str(outside), 0), ("../../escape", 1))
before = os.readlink(linked / "user.js")
state, summary, _ = sync()
chk("a linked user.js is reported, and the link is not replaced",
    (state, "could not safely change" in summary, os.readlink(linked / "user.js"),
     (linked / "chrome").exists()),
    ("synchronized", True, before, False))

# -- revert hands back the bytes, and waits to edit prefs.js while it runs ---
(mail / "prefs.js").write_text(
    'user_pref("toolkit.legacyUserProfileCustomizations.stylesheets", true);\n'
    'user_pref("mail.shell.checkDefaultClient", false);\n')
holders.append(424242)
state, summary, pids = sync(revert=True)
chk("a running Thunderbird is left until it exits",
    (state, pids, "when it closes" in summary), ("pending", [424242], True))
chk("prefs.js is not edited while it runs",
    "stylesheets" in (mail / "prefs.js").read_text(), True)
chk("the capture stays until that edit can be finished",
    str(mail) in manifest().get("thunderbird", {}).get("profiles", {}), True)
holders.clear()
state, _, pids = sync(revert=True)
kept = (mail / "prefs.js").read_text()
chk("once it has exited, the preference line is the only thing removed",
    (state, pids, "stylesheets" in kept, "checkDefaultClient" in kept,
     (mail / "chrome/hyprchroma.css").exists(), (mail / "chrome").exists(),
     (mail / "user.js").exists()),
    ("synchronized", [], False, True, False, False, False))
chk("and the capture is gone", "thunderbird" in manifest(), False)
E

# -- opt-in: only a recorded true turns it on --------------------------------
T=$(mktemp -d)
enabled() {
  printf '%s' "$1" > "$T/settings.json"
  ( SETTINGS_FILE=$T/settings.json
    source <(awk '/^target_key\(\) \{/,/^\}/' "$REPO/bin/hyprchroma")
    source <(awk '/^target_enabled\(\) \{/,/^\}/' "$REPO/bin/hyprchroma")
    target_enabled "$2" && echo on || echo off )
}
chk "no setting recorded: Thunderbird is off" "$(enabled '{}' thunderbird)" "off"
chk "a recorded true turns it on" "$(enabled '{"frameworks":{"thunderbird":true}}' thunderbird)" "on"
chk "a recorded false keeps it off" "$(enabled '{"frameworks":{"thunderbird":false}}' thunderbird)" "off"
chk "Pear still defaults on" "$(enabled '{}' pear)" "on"
rm -rf "$T"

# -- the panel, setup and documentation agree --------------------------------
P=$REPO/Panel.qml
chk "Pear's old row is now Additional Apps" \
  "$(grep -c 'target: "apps", label: "Additional Apps"' "$P")" "1"
chk "the drop-down lists Thunderbird and Pear Desktop (YouTube Music)" \
  "$(grep -c 'target: "thunderbird", label: "Thunderbird"' "$P"),$(grep -c 'target: "pear", label: "Pear Desktop (YouTube Music)"' "$P")" "1,1"
chk "that row opens the drop-down instead of toggling" \
  "$(grep -c 'if (entry.menu === true) root.appsOpen = !root.appsOpen' "$P")" "1"
chk "it opens in place: the framework list stays up, with no view or Back of its own" \
  "$(grep -c '&& !root.appsOpen' "$P"),$(grep -c 'text: "Back  (a)"' "$P"),$(grep -c '? "Additional Apps"' "$P")" "0,0,0"
chk "its rows are numbered on from the list, and only answer while it is open" \
  "$(grep -c 'String(root.visibleFrameworks.length + appRow.index + 1)' "$P"),$(grep -c '} else if (root.appsListShown) {' "$P")" "1,1"
chk "Thunderbird is off unless settings say true" \
  "$(grep -c 'thunderbird: frameworks.thunderbird === true' "$P")" "1"
U=$REPO/bin/hyprchroma-setup
chk "setup asks whether to include Thunderbird" "$(grep -c 'ask "Include Thunderbird"' "$U")" "1"
chk "and Pear Desktop under the same heading" \
  "$(grep -c 'ask "Include Pear Desktop (YouTube Music)"' "$U")" "1"
chk "setup does not offer to install Thunderbird" \
  "$(grep -c 'pacman -S --needed thunderbird' "$U")" "0"
chk "the README names the Thunderbird toggle" \
  "$(grep -c 'toggleThunderbird' "$REPO/README.md")" "1"

# Thunderbird 158 paints the window from many token sets, not one. Every
# custom property this build uses as a background, aside from per-account
# and status colors, has to be set or that surface stays on Thunderbird's
# own palette. Checked against the installed omni.ja when it is present.
if [[ -f /usr/lib/thunderbird/omni.ja ]]; then
  python3 - "$REPO" /usr/lib/thunderbird/omni.ja <<'E'
import re, sys, zipfile
from pathlib import Path
repo, omni = sys.argv[1:]
ns = {"__file__": repo + "/lib/hyprchroma-state"}
exec(compile(Path(ns["__file__"]).read_text(), "st", "exec"), ns)
sheet = ns["thunderbird_stylesheet"]({
    "mode": "dark", "background": "#17241e", "dark_background": "#101914",
    "foreground": "#d9e1d4", "accent": "#e8bd72", "selection": "#405648",
    "selection_foreground": "#f2ecd9", "muted": "#64766f"})
set_vars = set(re.findall(r"(--[a-z0-9-]+):", sheet))
skip = ("account-color", "tag-color", "warning", "critical", "success",
        "calendar", "vcard", "imgroup", "folder-color", "color-red",
        "color-blue", "color-purple", "color-orange", "color-pink",
        "color-teal", "color-magenta", "color-green", "color-yellow",
        "destructive", "icon-", "account-central-", "red-")
used = set()
z = zipfile.ZipFile(omni)
pat = re.compile(r"(?<![\w-])background(?:-color)?(?![\w-])\s*:\s*([^;]+);")
for name in z.namelist():
    if not (name.startswith("chrome/classic/skin/classic/messenger/") and name.endswith(".css")):
        continue
    text = z.read(name).decode("utf-8", "replace")
    for value in pat.findall(text):
        for var in re.findall(r"var\(\s*(--[a-z0-9-]+)", value):
            if any(part in var for part in skip):
                continue
            used.add(var)
missing = sorted(used - set_vars)
print(f"  {'PASS' if not missing else 'FAIL'} installed Thunderbird background tokens are set"
      + ("" if not missing else ": " + ", ".join(missing[:12])))
# The system-color rules the sheet names by selector: a Thunderbird that renames
# one would quietly bring the gray back, so each must still exist in this build.
every = "\n".join(z.read(n).decode("utf-8", "replace") for n in z.namelist() if n.endswith(".css"))
gone = [name for name in (".im-placeholder-screen", ".themeableSearchBox", "#listPaneBox",
                          ".contentTabInstance", ".calendar-enable-button", "#conv-top-info",
                          ".conv-nicklist-header", ".day-column-heading")
        if name not in every]
print(f"  {'PASS' if not gone else 'FAIL'} the rules named by selector still exist in this Thunderbird"
      + ("" if not gone else ": " + ", ".join(gone)))
E
fi
